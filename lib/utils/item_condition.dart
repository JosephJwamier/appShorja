/// أسماء حالات المنتج بالعربية — المصدر الوحيد لها في التطبيق.
///
/// كانت الترجمة مكرّرة في خمسة مواضع (تفاصيل المنتج، بطاقة الخريطة،
/// الفلاتر، إضافة منتج، نموذج الجوار)، فحين اختُصرت الحالات في الخادم
/// إلى أربع بقي بعضها يعرض `good` المتقاعدة ولا يعرف `unknown` الجديدة —
/// فتظهر للمستخدم كما هي بالإنجليزية.
///
/// تطابق CONDITION_CHOICES في core/models.py.
const Map<String, String> kConditionLabels = {
  'new': 'جديد',
  'like_new': 'شبه جديد',
  'used': 'مستعمل',
  'unknown': 'غير معلوم',
};

/// الاسم العربي للحالة.
///
/// أي قيمة غير معروفة — حالة متقاعدة في صفّ قديم، أو قيمة أضافها الخادم
/// ولم يعرفها التطبيق بعد — تُعرض «غير معلوم» لا كما هي: عرض `good` أو
/// `fair` للمستخدم العراقي يكشف تفاصيل داخلية بلغة لا يقرؤها، وهو أسوأ
/// من الاعتراف بأن الحالة غير محدّدة.
String conditionLabel(String? code) =>
    kConditionLabels[code] ?? kConditionLabels['unknown']!;
